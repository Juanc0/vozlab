import type { WorkspaceRole } from '@vozlab/shared-types';
import type { DbTransaction } from './Transaction.js';

export type AuthProvider = 'OIDC_INSTITUTIONAL' | 'ANONYMOUS_EVENT';

/** Internal user projection; never returned verbatim to other users. */
export interface AuthUser {
  id: string;
  email: string | null;
  fullName: string | null;
  provider: AuthProvider;
  providerUserId: string | null;
  authorHash: string;
  anonymousAlias: string | null;
  systemRole: string;
  sessionsValidAfter: Date | null;
}

export interface NewOidcUser {
  /** IdP `sub`. */
  providerUserId: string;
  /** Issuer URL of the identity provider. */
  issuer: string;
  email: string | null;
  fullName: string | null;
  /** Random 64-hex pseudonym generated by the use case (ADR-0013). */
  authorHash: string;
  /**
   * Whether the IdP asserted the email as verified.
   * `true` → safe to link an existing account by email.
   * `false` / `null` → never link by email (create a new account).
   */
  emailVerified: boolean | null;
}

export interface NewExternalIdentityInput {
  issuer: string;
  subject: string;
  email: string | null;
  emailVerified: boolean | null;
  fullName: string | null;
  authorHash: string;
  /**
   * Pseudonymous username for the admin's direct-add lookup (v6/TASK-03,
   * B14), derived from the IdP profile by the login use case. Optional:
   * a null handle keeps the user unfindable by handle, never blocks login.
   */
  handle?: string | null;
  /** Global identity ID from the router DB (D8). */
  globalIdentityId?: string | null;
}

export interface NewAnonymousUser {
  alias: string;
  /** Random 64-hex pseudonym generated by the caller. */
  authorHash: string;
}

export interface UserWorkspace {
  id: string;
  slug: string;
  name: string;
  role: WorkspaceRole;
}

/**
 * Port: identity rows in the tenant's physical DB (`auth.users`).
 *
 * `findOrCreateOidcUser` is an upsert, not a read-then-write in the use case:
 * concurrent callbacks for the same IdP subject must produce exactly one row
 * (backed by `uniq_users_provider_provider_user`).
 */
export interface IUserRepository {
  findById(userId: string, tid: string): Promise<AuthUser | null>;
  findByHandle(handle: string, tid: string): Promise<AuthUser | null>;
  findOrCreateOidcUser(input: NewOidcUser, tid: string): Promise<AuthUser>;

  /**
   * Find or create a user by external identity (issuer, subject).
   *
   * 1. If (issuer, subject) exists in external_identities → update profile, return user.
   * 2. If not exists and email belongs to another account → ERR_ACCOUNT_LINK_CONFLICT.
   * 3. If no email conflict → create user + external_identity row.
   *
   * Email linking only happens when emailVerified === true.
   */
  findOrCreateByExternalIdentity(
    input: NewExternalIdentityInput,
    tid: string
  ): Promise<AuthUser>;
  createAnonymousUser(
    input: NewAnonymousUser,
    tid: string,
    tx?: DbTransaction
  ): Promise<AuthUser>;
  listWorkspaces(userId: string, tid: string): Promise<UserWorkspace[]>;
  /**
   * v6/TASK-09 (B7): delete the anonymous event guests with no activity
   * signal since `cutoff` — the account itself, its memberships, its audit
   * trail and its refresh-token rotations are all older than the cutoff.
   * Cascade removes memberships and tokens; `membership_events` (no FK) and
   * graph authorship (`author_hash`, opaque) survive by design.
   * Returns the number of guests removed.
   */
  removeInactiveGuests(tid: string, cutoff: Date, tx?: DbTransaction): Promise<number>;
}
